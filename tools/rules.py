r"""번역 용어 규칙(2026-10-10 사용자 확정) — merge_ko 가 합칠 때 바꾸고, build 가 남은 금지 표기를 막는다.
  주인공 伊藤恵美里 = «에미리»(애칭 エミリー 도) · アンジェ = «안제» · 水嶋理論 = «리론»(받아쓰기 ティロン·ディロン·ヒロン)
  堤パリン = «파린»(받아쓰기 パリィ·アリン) · 高橋 = «타카하시»(거센소리)
  ★바꾸기 전후 받침이 같은 것만(조사 그대로) — 받침이 달라지면 조사도 같이 볼 것.
"""
import re

TERMS = [
    (r'에밀리', '에미리'),
    (r'앙제|앙쥬', '안제'),
    (r'[틸딜]론', '리론'),
    (r'파리(?= 선배)', '파린'),
    (r'다카하시', '타카하시'),
]


def apply(t):
    for a, b in TERMS:
        t = re.sub(a, b, t)
    return t


def check(t):
    """금지 표기가 남았으면 그 표기 목록"""
    return [m.group() for a, _ in TERMS for m in re.finditer(a, t)]
